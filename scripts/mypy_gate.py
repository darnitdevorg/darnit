#!/usr/bin/env python3
"""Type-check gate: whole-repository mypy against a committed baseline.

Runs mypy with the root ``pyproject.toml`` configuration (every package under
``packages/*/src``) and compares its errors, with line numbers stripped, to
``.github/mypy-baseline.txt``.

The gate fails when:

* mypy reports an error that the baseline does not hold (a new error);
* mypy reports a hard-tier error (``attr-defined``, ``call-arg``,
  ``name-defined``) that the hard-tier allow-list does not hold, baselined
  or not: these name a symbol that does not exist and fail at runtime;
* the baseline holds a hard-tier error, or holds an error mypy no longer
  reports (run ``--update`` to shrink it);
* the hard-tier allow-list holds an error mypy no longer reports, or an
  entry without a reason;
* mypy itself fails (exit status other than 0 or 1, or output it cannot
  parse).

``--update`` rewrites the baseline from the current errors. It refuses when a
hard-tier error is not in the allow-list, and never writes hard-tier errors
to the baseline. The allow-list (``.github/mypy-hard-allowlist.txt``) is
edited by hand and must shrink to zero.

Run it in CI's environment: ``uv sync --all-extras`` (the attestation extra
provides sigstore, which several modules import), then

    uv run --all-extras python scripts/mypy_gate.py
    uv run --all-extras python scripts/mypy_gate.py --update
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from collections import Counter
from dataclasses import dataclass, field
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
BASELINE_PATH = REPO_ROOT / ".github" / "mypy-baseline.txt"
ALLOWLIST_PATH = REPO_ROOT / ".github" / "mypy-hard-allowlist.txt"

HARD_TIER_CODES = frozenset({"attr-defined", "call-arg", "name-defined"})

BASELINE_HEADER = """\
# mypy errors tolerated by scripts/mypy_gate.py, one per line, line numbers
# stripped. Generated by `uv run python scripts/mypy_gate.py --update`; do not
# add lines by hand. Hard-tier errors (attr-defined, call-arg, name-defined)
# never belong here; see .github/mypy-hard-allowlist.txt.
"""

# path[:line[:col][:end_line:end_col]]: severity: message  [code]
_LINE_RE = re.compile(r"^(?P<path>[^:\s][^:]*)(?::\d+)*: (?P<severity>error|note|warning): (?P<message>.*)$")
_CODE_RE = re.compile(r"\s\s\[(?P<code>[a-z0-9-]+)\]$")
_LINE_REF_RE = re.compile(r"\bline \d+\b")


class GateError(Exception):
    """mypy, the baseline, or the allow-list could not be read."""


def normalize(line: str) -> str | None:
    """Return the line-number-free form of a mypy error line, or None for other lines.

    Raises GateError for a line that is not a recognizable mypy message, so
    a crash or configuration error is never read as "no errors".
    """
    line = line.rstrip()
    if not line:
        return None
    match = _LINE_RE.match(line)
    if not match:
        raise GateError(f"unrecognized mypy output: {line!r}")
    if match["severity"] != "error":
        return None
    path = match["path"].replace("\\", "/")
    message = _LINE_REF_RE.sub("line N", match["message"])
    return f"{path}: error: {message}"


def error_code(error: str) -> str | None:
    match = _CODE_RE.search(error)
    return match["code"] if match else None


def is_hard_tier(error: str) -> bool:
    return error_code(error) in HARD_TIER_CODES


def parse_mypy_output(text: str) -> list[str]:
    errors = []
    for line in text.splitlines():
        normalized = normalize(line)
        if normalized is not None:
            errors.append(normalized)
    return errors


def load_baseline(text: str) -> Counter[str]:
    return Counter(line for line in text.splitlines() if line.strip() and not line.startswith("#"))


def load_allowlist(text: str) -> Counter[str]:
    """Parse the hard-tier allow-list: each entry needs a ``#`` reason line directly above it."""
    entries: Counter[str] = Counter()
    reason = False
    for number, line in enumerate(text.splitlines(), start=1):
        if not line.strip():
            reason = False
        elif line.startswith("#"):
            reason = bool(line.lstrip("#").strip())
        else:
            if not reason:
                raise GateError(f"hard-tier allow-list line {number} has no '# reason' line above it")
            if not is_hard_tier(line):
                raise GateError(f"hard-tier allow-list line {number} is not a hard-tier error: {line}")
            entries[line] += 1
    return entries


@dataclass
class GateResult:
    total: int
    new: list[str] = field(default_factory=list)
    hard: list[str] = field(default_factory=list)
    allowed_hard: list[str] = field(default_factory=list)
    hard_in_baseline: list[str] = field(default_factory=list)
    stale_baseline: list[str] = field(default_factory=list)
    stale_allowlist: list[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not (self.new or self.hard or self.hard_in_baseline or self.stale_baseline or self.stale_allowlist)


def _excess(current: Counter[str], allowed: Counter[str]) -> list[str]:
    return sorted((current - allowed).elements())


def compare(current: list[str], baseline: Counter[str], allowlist: Counter[str]) -> GateResult:
    """Compare current mypy errors to the baseline and the hard-tier allow-list."""
    counts = Counter(current)
    hard = Counter({e: n for e, n in counts.items() if is_hard_tier(e)})
    soft = counts - hard
    soft_baseline = Counter({e: n for e, n in baseline.items() if not is_hard_tier(e)})
    return GateResult(
        total=len(current),
        new=_excess(soft, soft_baseline),
        hard=_excess(hard, allowlist),
        allowed_hard=sorted((hard & allowlist).elements()),
        hard_in_baseline=sorted(e for e in baseline.elements() if is_hard_tier(e)),
        stale_baseline=_excess(soft_baseline, soft),
        stale_allowlist=_excess(allowlist, hard),
    )


def render(result: GateResult, baseline_size: int) -> str:
    out = []

    def section(title: str, lines: list[str]) -> None:
        if lines:
            out.append(f"\n{title} ({len(lines)}):")
            out.extend(f"  {line}" for line in lines)

    section(
        "FAIL hard-tier errors (attr-defined, call-arg, name-defined); fix them, baselining is not allowed", result.hard
    )
    section("FAIL new errors not in .github/mypy-baseline.txt", result.new)
    section("FAIL hard-tier errors in the baseline; remove them and fix the code", result.hard_in_baseline)
    section(
        "FAIL baseline entries mypy no longer reports; run `uv run python scripts/mypy_gate.py --update`",
        result.stale_baseline,
    )
    section("FAIL hard-tier allow-list entries mypy no longer reports; delete them", result.stale_allowlist)
    section("Allowed hard-tier errors (.github/mypy-hard-allowlist.txt, must shrink to zero)", result.allowed_hard)
    verdict = "PASS" if result.ok else "FAIL"
    out.append(
        f"\nmypy gate: {verdict}. {result.total} errors; baseline {baseline_size}; "
        f"new {len(result.new)}; hard-tier {len(result.hard)} "
        f"(+{len(result.allowed_hard)} allow-listed); stale {len(result.stale_baseline) + len(result.stale_allowlist)}."
    )
    return "\n".join(out)


def run_mypy(extra_args: list[str]) -> list[str]:
    cmd = [
        sys.executable,
        "-m",
        "mypy",
        "--no-error-summary",
        "--no-pretty",
        "--no-color-output",
        "--hide-error-context",
        "--show-error-codes",
        *extra_args,
    ]
    proc = subprocess.run(cmd, cwd=REPO_ROOT, capture_output=True, text=True)
    if proc.returncode not in (0, 1):
        raise GateError(f"mypy exited {proc.returncode}:\n{proc.stdout}{proc.stderr}")
    errors = parse_mypy_output(proc.stdout)
    if proc.returncode == 1 and not errors:
        raise GateError(f"mypy exited 1 without reporting an error:\n{proc.stdout}{proc.stderr}")
    return errors


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8") if path.exists() else ""


def update(current: list[str], allowlist: Counter[str], baseline_path: Path) -> int:
    """Rewrite the baseline from ``current``; refuse if a hard-tier error is not allow-listed."""
    hard = _excess(Counter(e for e in current if is_hard_tier(e)), allowlist)
    if hard:
        print("Refusing to update the baseline: hard-tier errors cannot be baselined. Fix them:")
        for line in hard:
            print(f"  {line}")
        return 1
    soft = sorted(e for e in current if not is_hard_tier(e))
    baseline_path.write_text(BASELINE_HEADER + "".join(f"{e}\n" for e in soft), encoding="utf-8")
    print(f"Wrote {len(soft)} entries to {baseline_path}.")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--update", action="store_true", help="rewrite the baseline from the current errors")
    parser.add_argument("--baseline", type=Path, default=BASELINE_PATH, help=argparse.SUPPRESS)
    parser.add_argument("--allowlist", type=Path, default=ALLOWLIST_PATH, help=argparse.SUPPRESS)
    parser.add_argument("mypy_args", nargs="*", help="extra arguments passed to mypy (after --)")
    args = parser.parse_args(argv)

    try:
        allowlist = load_allowlist(_read(args.allowlist))
        baseline = load_baseline(_read(args.baseline))
        current = run_mypy(args.mypy_args)
    except GateError as e:
        print(f"mypy gate: ERROR. {e}")
        return 2

    if args.update:
        return update(current, allowlist, args.baseline)

    result = compare(current, baseline, allowlist)
    print(render(result, sum(baseline.values())))
    return 0 if result.ok else 1


if __name__ == "__main__":
    sys.exit(main())
